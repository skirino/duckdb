#!/usr/bin/env python3
"""Write the engine's version header from a Bazel workspace status file.

Fills in the two values scripts/workspace_status.sh reports, which the one
translation unit that reports the version includes instead of reading the
defines CMake passes on the command line. Missing keys are an error rather than a
default: a build with no --workspace_status_command must fail, not report the
commit some earlier build had.

Usage: write_version_header.py <status file> [<status file> ...] -- <output>
"""
import sys

TEMPLATE = """// Generated by scripts/write_version_header.py -- do not edit.
//
// The engine reports its own commit and version from here, so a build describes
// the checkout it was made from. CMake takes the same two values from the command
// line (-DDUCKDB_SOURCE_ID, -DDUCKDB_VERSION) instead.
#ifndef DUCKDB_GENERATED_VERSION_INFO_HPP
#define DUCKDB_GENERATED_VERSION_INFO_HPP
#define DUCKDB_SOURCE_ID "{source_id}"
#define DUCKDB_VERSION "{version}"
#endif
"""


def main():
    args = sys.argv[1:]
    out = args[args.index("--") + 1]
    values = {}
    for path in args[: args.index("--")]:
        with open(path) as f:
            for line in f:
                key, _, value = line.strip().partition(" ")
                # The status script prefixes its keys so they land in the stable
                # status file; strip it to get the macro name.
                values.setdefault(key.removeprefix("STABLE_"), value)
    missing = [k for k in ("DUCKDB_SOURCE_ID", "DUCKDB_VERSION") if k not in values]
    if missing:
        sys.exit(f"{' and '.join(missing)} not in the workspace status; is "
                 f"--workspace_status_command set in .bazelrc?")
    with open(out, "w") as f:
        f.write(TEMPLATE.format(source_id=values["DUCKDB_SOURCE_ID"],
                                version=values["DUCKDB_VERSION"]))


if __name__ == "__main__":
    main()
#!/usr/bin/env python3
"""Bazel workspace status: report this checkout's commit and version.

Bazel runs this once per build and hands the KEY VALUE lines to every rule
through ctx.info_file, which is how a build gets a value that changes with the
checkout without changing the command line. CMake bakes the same two values from
git at configure time (CMakeLists.txt:443 and :501), so the recipes here mirror
those: `git log -1 --format=%H` truncated to 10 and lowercased for the commit,
release_version.txt's major.minor with the patch at 0 and the dev iteration at
`git rev-list --count HEAD` for the version.

Used two ways:
  workspace_status_command = this script, printing the KEY VALUE lines
  --write-header <status file> <output>, for the generated header rule
"""
import os
import subprocess
import sys

RELEASE_VERSION_FILE = "scripts/ci/release_version.txt"
KEYS = ("DUCKDB_SOURCE_ID", "DUCKDB_VERSION")


REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def git(*args):
    try:
        return subprocess.run(["git", "-C", REPO, *args], capture_output=True,
                              text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def commit_hash():
    head = git("log", "-1", "--format=%H")
    return head[:10].lower() if head else None


def library_version():
    release = open(os.path.join(REPO, RELEASE_VERSION_FILE)).read().strip()
    count = git("rev-list", "--count", "HEAD") or "0"
    return f"v{release}.0-dev{count}"


def status():
    values = {"DUCKDB_SOURCE_ID": commit_hash(), "DUCKDB_VERSION": library_version()}
    return {k: v for k, v in values.items() if v}


HEADER = """// Generated by scripts/workspace_status.py -- do not edit.
//
// The engine reports its own commit and version from here, so a build describes
// the checkout it was made from rather than whatever was current when this
// file's include was last written. CMake takes the same two values from the
// command line (-DDUCKDB_SOURCE_ID, -DDUCKDB_VERSION) instead.
#ifndef DUCKDB_GENERATED_VERSION_INFO_HPP
#define DUCKDB_GENERATED_VERSION_INFO_HPP

#ifdef DUCKDB_SOURCE_ID
#undef DUCKDB_SOURCE_ID
#endif
#define DUCKDB_SOURCE_ID "{source_id}"

#ifdef DUCKDB_VERSION
#undef DUCKDB_VERSION
#endif
#define DUCKDB_VERSION "{version}"

#endif
"""


def write_header(status_files, out_file):
    values = {}
    for status_file in status_files:
        with open(status_file) as f:
            for line in f:
                key, _, value = line.strip().partition(" ")
                if key in KEYS:
                    values[key] = value
    missing = [k for k in KEYS if k not in values]
    if missing:
        sys.exit(f"workspace status is missing {', '.join(missing)}; is "
                 f"--workspace_status_command set in .bazelrc?")
    with open(out_file, "w") as f:
        f.write(HEADER.format(source_id=values["DUCKDB_SOURCE_ID"],
                             version=values["DUCKDB_VERSION"]))


def main():
    if len(sys.argv) == 5 and sys.argv[1] == "--write-header":
        return write_header(sys.argv[2:4], sys.argv[4])
    for key, value in status().items():
        print(f"{key} {value}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
#!/usr/bin/env bash
# Bazel workspace status: report this checkout's commit and version.
#
# Bazel runs this once per build and hands the KEY VALUE lines to every rule
# through ctx.info_file, which is how a build gets a value that follows the
# checkout without putting it on the command line. CMake bakes the same two
# values from git at configure time (CMakeLists.txt:443 and :501), so the recipes
# here mirror those: `git log -1 --format=%H` truncated to 10 and lowercased for
# the commit, release_version.txt's major.minor with the patch at 0 and the dev
# iteration at `git rev-list --count HEAD` for the version.
#
# Used two ways:
#   workspace_status_command = this script, printing the KEY VALUE lines
#   --write-header <status file> <status file> <output>, for the header rule
#
# Bazel runs it with the workspace as the working directory, but the path is
# taken from the script itself so that holds either way.
set -euo pipefail

REPO="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "${REPO}" ]]; then
    REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
fi

source_id() {
    git -C "${REPO}" log -1 --format=%H 2>/dev/null | cut -c1-10 | tr '[:upper:]' '[:lower:]'
}

library_version() {
    local release count
    release="$(tr -d '[:space:]' < "${REPO}/scripts/ci/release_version.txt")"
    count="$(git -C "${REPO}" rev-list --count HEAD 2>/dev/null || echo 0)"
    echo "v${release}.0-dev${count}"
}

write_header() {
    local out="$4" source_id="" version="" file
    # Which of the two status files a key lands in depends on whether it is
    # STABLE_-prefixed, and which one ctx hands over has moved between Bazel
    # versions, so take whichever has them.
    for file in "$2" "$3"; do
        [[ -r "${file}" ]] || continue
        if [[ -z "${source_id}" ]]; then
            source_id="$(awk '$1 == "DUCKDB_SOURCE_ID" { print $2; exit }' "${file}")"
        fi
        if [[ -z "${version}" ]]; then
            version="$(awk '$1 == "DUCKDB_VERSION" { print $2; exit }' "${file}")"
        fi
    done
    if [[ -z "${source_id}" || -z "${version}" ]]; then
        echo "workspace status is missing DUCKDB_SOURCE_ID or DUCKDB_VERSION;" \
             "is --workspace_status_command set in .bazelrc?" >&2
        exit 1
    fi
    cat > "${out}" <<EOF
// Generated by scripts/workspace_status.sh -- do not edit.
//
// The engine reports its own commit and version from here, so a build describes
// the checkout it was made from rather than whatever was current when this
// file's include was last written. CMake takes the same two values from the
// command line (-DDUCKDB_SOURCE_ID, -DDUCKDB_VERSION) instead.
#ifndef DUCKDB_GENERATED_VERSION_INFO_HPP
#define DUCKDB_GENERATED_VERSION_INFO_HPP

#ifdef DUCKDB_SOURCE_ID
#undef DUCKDB_SOURCE_ID
#endif
#define DUCKDB_SOURCE_ID "${source_id}"

#ifdef DUCKDB_VERSION
#undef DUCKDB_VERSION
#endif
#define DUCKDB_VERSION "${version}"

#endif
EOF
}

if [[ "${1:-}" == "--write-header" ]]; then
    write_header "$@"
    exit 0
fi

if commit="$(source_id)" && [[ -n "${commit}" ]]; then
    echo "DUCKDB_SOURCE_ID ${commit}"
    echo "DUCKDB_VERSION $(library_version)"
fi